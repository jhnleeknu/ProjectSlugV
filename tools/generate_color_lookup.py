"""Generate the C++11 channel table from the pinned MAME reference executable."""
import hashlib
from pathlib import Path
import subprocess
import sys


def main():
    root = Path(__file__).resolve().parents[1]
    subprocess.run([sys.executable,str(root/'tools/inspect_color_reference.py')],check=True)
    data = (root/'artifacts/color_reference/channel_lookup.bin').read_bytes()
    if hashlib.sha256(data).hexdigest() != '1a35fd99068aba9ed9e05a97335f63ded453d32c8ddbb567c64a0d45da630ed4':
        raise ValueError('Pinned channel table unexpectedly changed')
    rows = ['    {%s},' % ', '.join(str(v) for v in data[i:i+4]) for i in range(0,128,4)]
    output = '// Generated by tools/generate_color_lookup.py from pinned MAME.\n'
    output += '// BSD-3-Clause; see tools/licenses/mame-colors.txt.\n'
    output += '// Columns: normal, dark, shadow, dark_shadow.\n'
    output += 'static const std::uint8_t kChannelLookup[32][4] = {\n'+'\n'.join(rows)+'\n};\n'
    (root/'engine/src/color_lookup.inc').write_text(output)


if __name__ == '__main__':
    main()
