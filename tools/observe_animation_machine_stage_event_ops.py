def find_null_callback_index(program):
    """An even WORD index d (op 08 offset: LONG at e8cc0 + sext(d)) whose ROM LONG is 0: 2986 refuses a null callback (cmpa.w #0,a0 -> beq 290e)."""
    for d in range(0,0x8000,2):
        for idx in (d,(0x10000-d)&0xffff):
            a=(0xe8cc0+sext(idx,2))&M32
            if a+4<=0x100000 and rom_long(program,a)==0 and idx!=0:return idx
    raise AssertionError('no null callback entry')


