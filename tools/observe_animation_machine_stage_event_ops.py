# ----------------------------------------------------------------------------------
# Independent model: the F3a model class (a M68000 subset interpreter that decodes the ORIGINAL ROM BYTES) extended by ORI to CCR, PEA and MULU.W and the F3b carry rule.  Calls leave the
# F3b ranges at a black-box entry (the F3a blocks, 43e34 43e22 43e08 28ae 2986 289e 49a58 2a00); the native exit state of the black box is replayed (registers at the next leader,
# RAM / PVC writes) and its carry is unknown (taken from the executed path).
# ----------------------------------------------------------------------------------
ModelError=f3a.ModelError;NeedFlag=f3a.NeedFlag
MASK=f3a.MASK;SIGN=f3a.SIGN


class F3bModel(f3a.F3Model):
    def __init__(self,program,bank_state,ram,regs,sr=None):
        super().__init__(program,bank_state,ram,regs,sr)
        self.last_kind=None;self.final=None
    def decode(self,pc):
        if pc in self.cache:return self.cache[pc]
        w=self.ext(pc);ins=None
        if w==0x003c:ins=dict(pc=pc,op='oricr',imm=self.ext(pc+2)&0xff,len=4)
        elif (w&0xffc0)==0x4840 and ((w>>3)&7)!=0:
            ea,pos=self.decode_ea((w>>3)&7,w&7,4,pc+2);ins=dict(pc=pc,op='pea',src=ea,len=pos-pc)
        elif (w&0xf1c0)==0xc0c0:
            ea,pos=self.decode_ea((w>>3)&7,w&7,2,pc+2);ins=dict(pc=pc,op='mulu',reg=(w>>9)&7,src=ea,len=pos-pc)
        if ins is None:return super().decode(pc)
        self.cache[pc]=ins;return ins
    def step(self,nl):
        pc=self.pc;ins=self.decode(pc);o=ins['op'];r=self.r;nxt=(pc+ins['len'])&M32
        self.last_kind={'jsr':'call','bsr':'call','bra':'jump','bcc':'jump','jmp':'jump','rts':'ret'}.get(o)
        if o=='oricr':
            for bit,name in ((0,'C'),(1,'V'),(2,'Z'),(3,'N'),(4,'X')):
                if (ins['imm']>>bit)&1:self.cc[name]=1
            self.pc=nxt
        elif o=='pea':
            loc=self.resolve(ins['src'],4);self.push32(loc[1]);self.pc=nxt
        elif o=='mulu':
            v=self.get(self.resolve(ins['src'],2),2);n='d%d'%ins['reg'];res=((r[n]&0xffff)*v)&M32;r[n]=res
            self.cc.update(N=int(bool(res&0x80000000)),Z=int(res==0),V=0,C=0);self.pc=nxt
        elif o=='bcc':
            try:taken=self.cond(ins['cond'])
            except NeedFlag as e:
                if pc not in CONSUMERS_B:raise ModelError('branch at %x on the unknown flag %s (not a declared carry consumer)'%(pc,e.names))
                j=len(self.leads)
                if j<len(self.nl):
                    succ=self.nl[j]['pc'];src='the next native leader after the branch is %x'%succ
                elif self.final is not None and self.final[1]:
                    succ=self.final[0];src='no native leader follows: the native run ended directly at %x'%succ
                else:raise ModelError('unknown carry at %x and no native successor leader'%pc)
                if succ not in (ins['target'],nxt):raise ModelError('native successor %x of %x is neither target %x nor fall-through %x'%(succ,pc,ins['target'],nxt))
                taken=succ==ins['target']
                self.evidence.append(dict(pc=hex(pc),flag='C',taken=taken,source='native executed path: %s (carry produced by a black box 289e / 2986)'%src))
            self.pc=ins['target'] if taken else nxt
        else:super().step(nl)


def replay_events_b(M,events,lo,hi):
    """Replay the black-box events (all of them by PCs outside the F3b ranges): RAM writes and PVC register writes (bank tracking)."""
    for e in events[lo:hi]:
        if in_b(e['pc']):raise ModelError('F3b-attributed event %s at %x inside a black-box slice'%(e['access'],e['pc']))
        a,n=e['address'],e['size']
        if e['region']=='ram' and e['access']=='write':M.mem_write(a,n,int(e['bytes'],16),log=False)
        elif e['region']=='pvc':M.pvc(a,int(e['bytes'],16))


def lead_of(M,pc):
    regs=dict(M.r);regs['pc']=pc;return regs


def run_segment(M,p,nl):
    events=p['events'];out=p['outgoing'];steps=0;M.nl=nl;M.final=(out['pc'],p['guard'] is None)
    unknown=dict(X=None,N=None,Z=None,V=None,C=None)
    if not in_b(M.pc):                                                # entry outside F3b (the dispatcher shell, the F3a prefix): replayed up to the first native leader
        hi=nl[0]['event_index'] if nl else len(events);replay_events_b(M,events,0,hi)
        if not nl:
            M.r.update({k:out[k] for k in REG16});M.pc=out['pc'];return 'end-in-blackbox'
        M.r.update({k:nl[0]['regs'][k] for k in REG16});M.pc=nl[0]['pc'];M.cc=dict(unknown)
    while True:
        pc=M.pc
        if pc in TRAP_SITES and pc==out['pc'] and p['guard'] is None:return 'stop-at-declared-trap'
        if not in_b(pc):
            if pc in LEAD_PCS:                                         # exit of the unit: a black-box entry (call / tail jump) or the return to the F3a block e91b0
                M.leads.append(lead_of(M,pc));e=len(M.leads)-1
                if e>=len(nl) or nl[e]['pc']!=pc:raise ModelError('exit to %x: the native leaders do not align at lead %d'%(pc,e))
                kind=M.last_kind;a7=M.r['a7'];ret=M.mem_read(a7,4,log=False) if a7<0x200000 else None
                hi=nl[e+1]['event_index'] if e+1<len(nl) else len(events)
                replay_events_b(M,events,nl[e]['event_index'],hi)
                if e+1<len(nl):
                    nx=nl[e+1]
                    if pc==EVAL_ENTRY:                                 # evaluator: the bundled caller branch of decision 3
                        if ret not in F3B_CALLERS:raise ModelError('evaluator entered with the unknown return LONG %x'%ret)
                        tz,tn=BUNDLED_CALLERS[ret]
                        if nx['pc'] not in (tz,tn):raise ModelError('evaluator return %x: next native leader %x is neither %x nor %x'%(ret,nx['pc'],tz,tn))
                        z=(nx['regs']['d0']&0xff)==0
                        if z!=(nx['pc']==tz):raise ModelError('evaluator return %x: D0.B = %02x but the branch went to %x'%(ret,nx['regs']['d0']&0xff,nx['pc']))
                        M.evidence.append(dict(pc=hex(ret),flag='Z',taken=nx['pc']==tz,source='D0.B of the evaluator result at the next native leader %x is %02x (decision 3 bundled BEQ.W of the caller)'%(nx['pc'],nx['regs']['d0']&0xff)))
                    elif kind=='call' or (kind=='jump' and pc==0xe9768):
                        if nx['pc']!=ret or nx['regs']['a7']!=(a7+4)&M32:raise ModelError('black box %x returned to %x with A7 %x, the model expects %x / %x'%(pc,nx['pc'],nx['regs']['a7'],ret,(a7+4)&M32))
                    M.r.update({k:nx['regs'][k] for k in REG16});M.pc=nx['pc'];M.cc=dict(unknown)
                    continue
                M.r.update({k:out[k] for k in REG16});M.pc=out['pc'];return 'end-in-blackbox'
            if pc==out['pc'] and p['guard'] is None:return 'stop-at-declared-pc'
            raise ModelError('control left the F3b ranges at %x (not a declared black-box entry)'%pc)
        if pc in START_SET:M.leads.append(lead_of(M,pc))
        steps+=1
        if steps>3000000:raise ModelError('model step limit')
        M.step(nl)


