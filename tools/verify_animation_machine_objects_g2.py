def pvc_image(bank):
    page = bytearray(8192)
    page[0x1ff0:0x1ff2] = (bank[1] & 0xffff).to_bytes(2, 'big')
    page[0x1ff2:0x1ff4] = (bank[2] & 0xffff).to_bytes(2, 'big')
    return bytes(page)


def pvc_apply(pvc, ports):
    """Independent PVC model (MAME formula through address_map.pvc_bank_update): returns the expected image and bank base after the PVC page WORD writes of `ports`."""
    img = bytearray(pvc)
    base = None
    for a, sz, v in ports:
        if 0x2fe000 <= a < 0x300000:
            if sz != 2 or a not in (0x2ffff0, 0x2ffff2):
                return None, None
            off = a - 0x2fe000
            img[off:off + 2] = v.to_bytes(2, 'big')
            ff8, ff9 = int.from_bytes(img[0x1ff0:0x1ff2], 'big'), int.from_bytes(img[0x1ff2:0x1ff4], 'big')
            base, ff8, ff9 = O.pvc_bank_update(ff8, ff9)
            img[0x1ff0:0x1ff2] = ff8.to_bytes(2, 'big')
            img[0x1ff2:0x1ff4] = ff9.to_bytes(2, 'big')
    return bytes(img), base


def norm_ports(events):
    """(address, size, value) with LONG events expanded into two WORD events (the Unicorn hook sees MOVE.L as one LONG store, the C++ port list expands PVC stores per WORD)."""
    out = []
    for a, sz, v in events:
        if sz == 4:
            out.append((a, 2, v >> 16))
            out.append((a + 2, 2, v & 0xffff))
        else:
            out.append((a, sz, v))
    return out


def native_ports(piece_ports):
    return norm_ports([(e[1], e[2], e[3]) for e in piece_ports])


def cpp_ports(ports):
    return norm_ports([(a, sz, v) for a, sz, v in ports])


