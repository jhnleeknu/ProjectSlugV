def sx16(v):
    return v - 0x10000 if v & 0x8000 else v


def forked_native_summary(st, stops):
    """Native flow in a forked child (a computed landing in the middle of an instruction can abort the Unicorn translator): returns native_summary or kind 'translator-abort'."""
    import pickle
    r, w = os.pipe()
    pid = os.fork()
    if pid == 0:
        try:
            os.close(r)
            data = pickle.dumps(native_summary(native_flow(st, stops, O.GLOBAL['fix_limit'])), protocol=4)
            with os.fdopen(w, 'wb') as f:
                f.write(data)
            os._exit(0)
        except BaseException:
            os._exit(3)
    os.close(w)
    chunks = []
    while True:
        b = os.read(r, 1 << 16)
        if not b:
            break
        chunks.append(b)
    os.close(r)
    os.waitpid(pid, 0)
    if not chunks:
        return dict(kind='translator-abort', guard=None, stop=None)
    return pickle.loads(b''.join(chunks))


def negatives_task(arg):
    kind, payload = arg
    srv = server()
    base = O.load_state(payload['base'])
    out = collections.Counter()
    fails = []
    detail = []

    def expect_error(pc, carry, stop, err, label):
        st = dict(base, pc=pc)
        cur = start_state(st, carry)
        seg = cpp_segment(srv, cur, stop)
        ok = seg['kind'] == 'error' and seg['error'] == err and seg['preserved']
        out[label + (':ok' if ok else ':DIFF')] += 1
        if not ok and len(fails) < 20:
            fails.append([label, hx(pc), carry, seg['kind'], seg.get('error'), err])
        return ok

    def expect_stop(pc, carry, label):
        st = dict(base, pc=pc)
        cur = start_state(st, carry)
        seg = cpp_segment(srv, cur, pc)
        ok = seg['kind'] == 'ok' and seg['cur'] == cur and seg['ports'] == [] and seg['reads'] == 0
        out[label + (':ok' if ok else ':DIFF')] += 1
        if not ok and len(fails) < 20:
            fails.append([label, hx(pc), carry, seg['kind'], seg.get('error')])
    if kind == 'interior':
        u, pcs = payload['unit'], payload['pcs']
        for pc in pcs:
            for carry in (0, 1, 2):
                expect_error(pc, carry, IMPOSSIBLE_STOP, UNSUPPORTED_UNIT[u], 'interior-%s' % UNAME[u])
    elif kind == 'odd':
        u, pcs = payload['unit'], payload['pcs']
        for pc in pcs:
            expect_error(pc, 0, IMPOSSIBLE_STOP, UNALIGNED_PC, 'odd-%s' % UNAME[u])
            expect_error(pc, 2, pc & ~1, UNALIGNED_PC, 'odd-%s-evenstop' % UNAME[u])
    elif kind == 'zero':
        u, pcs = payload['unit'], payload['pcs']
        for pc in pcs:
            for carry in (0, 1, 2):
                expect_stop(pc, carry, 'zero-step-%s' % UNAME[u])
    elif kind == 'unrouted':
        for pc in UNROUTED_PROBES:
            for carry in (0, 1, 2):
                expect_error(pc, carry, IMPOSSIBLE_STOP, UNSUPPORTED_MACHINE, 'unrouted-ram')
                expect_stop(pc, carry, 'unrouted-ram-zero-step')
    elif kind == 'landing':
        env = ENV[0]
        j = O.load_state(payload['jt_start'])
        stops = tuple(sorted(O.fix_stops(env)))
        lo, hi = 0x44ade, 0x45176
        for v in payload['values']:
            st = dict(j, regs=dict(j['regs'], d7=v))
            landing = (0x44ae2 + sx16(v & 0xffff)) & 0xffffff
            nsum = forked_native_summary(st, stops + (landing,))
            row = dict(d7=v, landing=landing, native=nsum, native_pcs_ref=None)
            cur = start_state(st, 1)
            # (a) the stop at the landing PC is reached directly after the JMP, whatever the landing is (even PC)
            if landing & 1:
                ok_stop = None
            else:
                seg = cpp_segment(srv, cur, landing)
                ok_stop = seg['kind'] == 'ok' and seg['cur']['pc'] == landing and seg['ports'] == [] and all(seg['cur']['regs'][k] == cur['regs'][k] for k in KEYS) and seg['cur']['ram'] == cur['ram']
                out['landing-stop-ok' if ok_stop else 'landing-stop-DIFF'] += 1
            # (b) no stop: classify the C++ outcome
            seg = cpp_segment(srv, cur, IMPOSSIBLE_STOP)
            interior_in_range = (lo <= landing < hi) and landing not in env.starts and not (landing & 1)
            if landing & 1:
                exp = UNALIGNED_PC
                kind_ = 'odd'
            elif interior_in_range:
                exp = UNSUPPORTED_UNIT[20]
                kind_ = 'interior'
            else:
                exp = None
                kind_ = 'start' if landing in env.starts else 'outside'
            row.update(kind=kind_, cpp=(seg['error'] if seg['kind'] == 'error' else seg['kind']), preserved=seg.get('preserved'))
            if exp is not None:
                ok = seg['kind'] == 'error' and seg['error'] == exp and seg['preserved']
                out['landing-%s-exact:%s' % (kind_, 'ok' if ok else 'DIFF')] += 1
                if not ok and len(fails) < 20:
                    fails.append(['landing', hx(v), hx(landing), seg['kind'], seg.get('error'), exp])
                if kind_ == 'interior':
                    out['landing-interior-native:%s' % (nsum['kind'] + ('/' + str(nsum['guard']) if nsum['guard'] else ''))] += 1
                if kind_ == 'odd':
                    out['landing-odd-native:%s' % (nsum['kind'] + ('/' + str(nsum['guard']) if nsum['guard'] else ''))] += 1
            else:
                out['landing-%s-cpp:%s' % (kind_, seg['error'] if seg['kind'] == 'error' else seg['kind'])] += 1
                if seg['kind'] == 'error' and not seg['preserved']:
                    out['landing-%s-NOT-PRESERVED' % kind_] += 1
            if len(detail) < 6000:
                detail.append(row)
    return dict(kind=kind, unit=payload.get('unit'), counts=dict(out), fails=fails, detail=detail)


def negatives_stage(workers, base_row, jt_start):
    env = ENV[0]
    tasks = []
    for u in UIDS:
        c = env.contracts[u]
        starts = set(c['starts'])
        even = [pc for lo, hi in c['ranges'] for pc in range(lo, hi, 2)]
        odd = [pc for lo, hi in c['ranges'] for pc in range(lo + 1, hi, 2)]
        stops = set(c['starts']) | set(pc for pc, uu in env.boundary.items() if uu == u) | set(G2.BOUNDARY_NAMED[u].get('written', ()))
        interior = [pc for pc in even if pc not in starts]
        for i in range(0, len(interior), 400):
            tasks.append(('interior', dict(unit=u, pcs=interior[i:i + 400], base=base_row)))
        for i in range(0, len(odd), 400):
            tasks.append(('odd', dict(unit=u, pcs=odd[i:i + 400], base=base_row)))
        zero = sorted(stops)
        for i in range(0, len(zero), 100):
            tasks.append(('zero', dict(unit=u, pcs=zero[i:i + 100], base=base_row)))
    tasks.append(('unrouted', dict(base=base_row)))
    values = list(range(0, 0x698)) + [0x8000, 0xfffc, 0xfff8, 0xfffe, 0xf000, 0x7ffe, 0x7fff, 0xff00, 0xfe00, 0xfd00, 0xf800]
    for i in range(0, len(values), 150):
        tasks.append(('landing', dict(values=values[i:i + 150], base=base_row, jt_start=jt_start)))
    ctx = multiprocessing.get_context('fork')
    with ctx.Pool(workers, initializer=pool_init) as pool:
        res = list(pool.imap(negatives_task, tasks, chunksize=1))
    return res


