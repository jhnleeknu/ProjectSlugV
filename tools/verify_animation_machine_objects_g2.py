def make_node_task(case, rows, dump_ok):
    def node_task(run, node, exit_state, partial):
        env = ENV[0]
        key = (run.frame, node['seq'])
        rec = rows.get(key)
        out = dict(frame=run.frame, seq=node['seq'], cb=node['cb'], a6=node['a6'], partial=bool(partial))
        if rec is None:
            out['class'] = 'DIFF:not-recorded'
            return out
        entry = dict(ram=node['entry_ram'], regs=dict(node['entry_regs']), pc=0x2ab8, bank=tuple(node['entry_bank']), ccr=0)
        rec_ok = (rec['entry'] == node['entry_digest'] and rec['exit'] == node['exit_digest'] and rec['a6'] == node['a6'] and rec['cb'] == node['cb'] and
                  rec['partial'] == bool(partial) and rec['depth'] == node['depth'])
        out['recorded_ok'] = rec_ok
        nat = native_flow(entry, (PASS_PC,), O.NAT_LIMIT)
        # native regeneration vs the recorded row / dumps
        nat_ok = True
        if not partial:
            fs = nat.states[-1]
            nat_ok = nat.final['kind'] == 'stop' and S.state_blob_digest(fs['ram'], fs['regs'], fs['pc'], fs['bank']) == node['exit_digest']
        else:
            nat_ok = nat.final['kind'] == 'guard' and rec['final'] == 'guard' and rec['guard'] == nat.final['detail']['kind']
        if rec.get('dumps'):
            st = [O.g1_digest(s) for s in nat.states]
            nat_ok = nat_ok and [x['state'] for x in rec['dumps']['states']] == st and rec['dumps']['exit']['state'] == st[-1] and rec['dumps']['entry']['state'] == st[0]
            dump_ok[0] += 1
        out['native_ok'] = bool(nat_ok)
        out['insns'] = rec['insns']
        res, final_cur = run_cpp_flow(server(), nat, entry, 0, 'n%d/%d/%d' % (case, run.frame, node['seq']))
        # the recorded exit digest, recomputed from the actual C++ output of the last phase
        exit_ok = None
        if nat.final['kind'] == 'stop' and final_cur is not None:
            c = final_cur
            ff8 = int.from_bytes(c['pvc'][0x1ff0:0x1ff2], 'big')
            ff9 = int.from_bytes(c['pvc'][0x1ff2:0x1ff4], 'big')
            exit_ok = S.state_blob_digest(c['ram'], c['regs'], c['pc'], (c['bank'], ff8, ff9)) == node['exit_digest'] and node['exit_digest'] == rec['exit']
        out['exit_ok'] = exit_ok
        out['res'] = res
        cls = flow_class(res)
        if cls in ('match', 'match-partial') and not (rec_ok and nat_ok and (exit_ok or (exit_ok is None and cls == 'match-partial'))):
            cls = 'DIFF:record'
        if cls.startswith('guard:') and not (rec_ok and nat_ok):
            cls = 'DIFF:record'
        out['class'] = cls
        return out
    return node_task


