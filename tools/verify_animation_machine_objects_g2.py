class Server(object):
    """One batch harness process, used by one worker (diag = the diagnostic copy)."""
    def __init__(self, diag=False):
        self.dir = Path(tempfile.mkdtemp(prefix='g2_run_', dir=str(RUN_ROOT[0])))
        self.proc = subprocess.Popen([str(EXE[1] if diag else EXE[0])] + list(EXE[2]), stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True, close_fds=False)
        self.calls = 0

    def call(self, cur, stop, external=0):
        """One run_animation_machine call.  cur = dict(ram, regs, pc, carry, pvc, bank).  Returns dict(ok, error, ...)."""
        d = self.dir
        paths = [d / n for n in ('ram_in', 'pvc_in', 'ram_out', 'pvc_out', 'ports_out')]
        paths[0].write_bytes(cur['ram'])
        paths[1].write_bytes(cur['pvc'])
        args = [str(cur['regs'][k]) for k in KEYS] + [str(cur['pc']), str(cur['carry']), str(cur['bank']), str(stop), str(external)] + [str(p) for p in paths]
        self.proc.stdin.write(' '.join(args) + '\n')
        self.proc.stdin.flush()
        first = self.proc.stdout.readline()
        second = self.proc.stdout.readline()
        assert first and second, 'batch harness died'
        self.calls += 1
        res = json.loads(first)
        error = '' if second.strip() == '-' else bytes.fromhex(second.strip()).decode()
        raw = paths[4].read_bytes()
        ports = [(int.from_bytes(raw[i + 1:i + 5], 'big'), raw[i], int.from_bytes(raw[i + 5:i + 9], 'big')) for i in range(0, len(raw), 9)]
        out = dict(ok=res['ok'], error=error, diag_pc=res.get('diag_pc'), ports=ports, reads=res['external_reads'], status=res['status'], marker=(raw == MARKER and res['external_reads'] == 0x12345678 and res['status'] == 1),
                   cur=dict(ram=paths[2].read_bytes(), pvc=paths[3].read_bytes(), regs={k: res[k] for k in KEYS}, pc=res['pc'], carry=res['carry'], bank=res['bank_base']))
        return out


