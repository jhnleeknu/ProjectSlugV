def carry_table_cpp():
    """The carry preserving PCs of animation_machine.cpp (carry_preserving_pc).  The G2 consumers are derived from the actual C++ behavior (exact unknown-carry error at the block start), never from a source parse."""
    machine = (ROOT / 'engine/src/animation_machine.cpp').read_text()
    i = machine.index('bool carry_preserving_pc')
    j = machine.index('default:', i)
    return set(int(x, 16) for x in re.findall(r'case (0x[0-9a-f]+):', machine[i:j]))


def native_block(st, start, unit, limit=400):
    """Native single block step: run from `st` until the first instruction (after >= 1) that is a contract block start / TRAP / outside the unit."""
    env = ENV[0]
    m = O.make_machine(env, st)
    c = m.cpu
    box = dict(n=0, stop=None)

    def hook(uc, pc, size, user):
        if box['n'] > 0 and (pc in env.starts or env.unit_of(pc) != unit or pc in env.traps or pc in env.boundary):
            box['stop'] = pc
            uc.emu_stop()
            return
        box['n'] += 1
    c.hook_add(O.UC_HOOK_CODE, hook, begin=0, end=0xfffff)
    m.fetch_unmapped = None
    m.odd = None
    m.invalid = None
    m.intr = None
    err = None
    try:
        c.emu_start(st['pc'], 0xffffff, count=limit)
    except unicorn.UcError as e:
        err = str(e)
    if box['stop'] is not None:
        fin = O.capture(m)
        ext = sum(1 for a, sz in m.dev_reads if (a & 0xffffff) == 0xd00046 and sz == 1)
        return dict(kind='stop', pc=box['stop'], state=fin, ports=native_ports(m.ports), ext=ext, n=box['n'])
    g = O.guard_of(m)
    if g:
        return dict(kind='guard', guard=g[0], n=box['n'])
    return dict(kind='limit' if not err else 'unicorn-error', n=box['n'])


