class LFlow(O.Flow):
    """The pinned native Flow plus the executed PC list of every piece (first arrival analysis) and the external (d00046) read count of every piece."""
    def __init__(self, *a, **k):
        O.Flow.__init__(self, *a, **k)
        self.dmark = 0

    def new_piece(self, unit, idx):
        O.Flow.new_piece(self, unit, idx)
        self.piece['pcs'] = []

    def on_code(self, uc, pc, size, user):
        O.Flow.on_code(self, uc, pc, size, user)
        if self.pause is None:
            self.piece['pcs'].append(pc)

    def close_piece(self, m, idx):
        O.Flow.close_piece(self, m, idx)
        p = self.pieces[-1]
        devs = list(m.dev_reads) if self.mode == 'split' else list(m.dev_reads[self.dmark:])
        if self.mode != 'split':
            self.dmark = len(m.dev_reads)
        p['ext'] = sum(1 for a, sz in devs if (a & 0xffffff) == 0xd00046 and sz == 1)
        p['dev_other'] = len(devs) - p['ext']


