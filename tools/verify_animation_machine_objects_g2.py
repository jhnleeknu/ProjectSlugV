def diff_state(cpp, nat_state, ports_pvc_expect=None):
    """Differences between a C++ output state and a native boundary state (full RAM, 16 registers, PC, bank base, ff8 / ff9)."""
    d = []
    if cpp['pc'] != nat_state['pc']:
        d.append('pc')
    for k in KEYS:
        if cpp['regs'][k] != nat_state['regs'][k]:
            d.append(k)
    if cpp['ram'] != nat_state['ram']:
        first = next(i for i in range(65536) if cpp['ram'][i] != nat_state['ram'][i])
        d.append('ram@%x' % first)
    b = nat_state['bank']
    if cpp['bank'] != b[0]:
        d.append('bank')
    if int.from_bytes(cpp['pvc'][0x1ff0:0x1ff2], 'big') != (b[1] & 0xffff) or int.from_bytes(cpp['pvc'][0x1ff2:0x1ff4], 'big') != (b[2] & 0xffff):
        d.append('ff8ff9')
    if ports_pvc_expect is not None and cpp['pvc'] != ports_pvc_expect:
        d.append('pvc-image')
    return d


def wait_info(cur):
    """The declared wait (sound 3aea / sprite cda4) computed from the C++ state; None when the PC is no declared wait."""
    pc = cur['pc']
    regs = cur['regs']
    ram = cur['ram']
    def word(a):
        o = a & 0xffff
        return (ram[o] << 8) | ram[(o + 1) & 0xffff]
    if pc == 0x3aea:
        return dict(pc=pc, kind='sound', live=word((regs['a5'] - 0x328c) & M32), compared=regs['d1'] & 0xffff, released=[[0x104d74, 2, 0xffff]])
    if pc == 0xcda4:
        want = regs['d4'] & 0xffff
        return dict(pc=pc, kind='sprite', live=word((regs['a5'] + 0xd34) & M32), compared=want, released=[[0x108d34, 2, want]])
    return None


def apply_release(cur, w):
    ram = bytearray(cur['ram'])
    for a, sz, v in w['released']:
        for i, b in enumerate(v.to_bytes(sz, 'big')):
            ram[(a + i) & 0xffff] = b
    out = dict(cur)
    out['ram'] = bytes(ram)
    return out


def native_wait_rows(waits):
    return [dict(pc=w['pc'], kind=w['kind'], live=w['live'], compared=w['compared'], released=[list(x) for x in w['released']]) for w in waits]


def cpp_segment(srv, cur, stop):
    """One C++ phase (run_animation_machine calls until the stop, with the declared wait releases between them).  Every call resumes from the previous actual output."""
    ports, reads, waits, c = [], 0, [], cur
    for _ in range(WAIT_LIMIT):
        r = srv.call(c, stop)
        if not r['ok']:
            preserved = r['marker'] and r['cur']['ram'] == c['ram'] and r['cur']['pvc'] == c['pvc'] and r['cur']['regs'] == c['regs'] and r['cur']['pc'] == c['pc'] and \
                r['cur']['carry'] == c['carry'] and r['cur']['bank'] == c['bank']
            return dict(kind='error', error=r['error'], diag_pc=r.get('diag_pc'), preserved=bool(preserved), cur=c, ports=ports, reads=reads, waits=waits)
        ports += r['ports']
        reads += r['reads']
        c = r['cur']
        if r['status'] == 1:
            w = wait_info(c)
            if w is None:
                return dict(kind='bad-wait', pc=c['pc'], cur=c, ports=ports, reads=reads, waits=waits)
            waits.append(w)
            c = apply_release(c, w)
            continue
        return dict(kind='ok', cur=c, ports=ports, reads=reads, waits=waits)
    return dict(kind='wait-limit', cur=c, ports=ports, reads=reads, waits=waits)


# --------------------------------------------------------------------------------------------------------------------- one native flow vs the C++ (continuous + split)
def phase_groups(nat):
    """Group the native pieces into C++ phases.  The C++ stop is the first arrival of the PC at a block start: when the boundary PC also occurs among the executed PCs of the phase
    before the arrival, the phase is merged with the next piece."""
    n = len(nat.pieces)
    kind_ = nat.final['kind']
    groups = []
    i = 0
    while i < n:
        j = i
        while True:
            last = (j == n - 1)
            if last and nat.final['kind'] != 'stop':
                break
            target = nat.states[nat.pieces[j]['end']]['pc']
            if kind_ != 'stop' and (target & 1):
                j = n - 1                  # native odd-PC guard: the C++ fails at the transfer, no stop PC exists
                break
            seen = set()
            for k in range(i, j + 1):
                seen.update(nat.pieces[k]['pcs'])
            if target in seen and not last:
                j += 1
                continue
            break
        groups.append((i, j))
        i = j + 1
    return groups


def native_summary(nat):
    f = nat.final
    return dict(kind=f['kind'], guard=(f['detail'].get('kind') if f['kind'] == 'guard' else None), stop=(f['detail'].get('pc') if f['kind'] == 'stop' else None))


def expected_error_ok(native_guard_kind, err):
    return err in GUARD_TABLE.get(native_guard_kind, ())


def phase_unit_set(nat, a, b):
    return sorted(set(nat.pieces[k]['unit'] for k in range(a, b + 1)))


def native_phase_expect(nat, a, b):
    ports, ext = [], 0
    for k in range(a, b + 1):
        ports += nat.pieces[k]['ports']
        ext += nat.pieces[k]['ext']
    return native_ports(ports), ext


def waits_equal(cpp_waits, nat_waits):
    return [dict(pc=w['pc'], kind=w['kind'], live=w['live'], compared=w['compared'], released=w['released']) for w in cpp_waits] == nat_waits


def compare_ok_segment(seg, begin, nstate, nat_ports, nat_ext):
    """Differences between an ok C++ segment and the native end state / ordered ports / external reads (begin = the C++ start of the segment)."""
    exp_pvc, exp_base = pvc_apply(begin['pvc'], seg['ports'])
    d = diff_state(seg['cur'], nstate, exp_pvc)
    if cpp_ports(seg['ports']) != nat_ports:
        d.append('ports')
    if seg['reads'] != nat_ext:
        d.append('external-reads')
    if exp_base is not None and seg['cur']['bank'] != exp_base:
        d.append('bank-model')
    return d


def carry_check(res, cur, nstate):
    if nstate['ccr'] is not None and cur['carry'] in (1, 2):
        res['carry_checked'] += 1
        if (cur['carry'] == 2) != bool(nstate['ccr'] & 1):
            res['carry_bad'] += 1
            res['errors'].append(('carry', cur['pc'], cur['carry'], nstate['ccr']))
    elif cur['carry'] == 0:
        res['carry_unknown'] += 1


def reached_pcs(nat, a, b):
    out = set()
    for k in range(a, b + 1):
        out.update(nat.pieces[k]['pcs'])
    return out


def guard_detail(nat):
    """(address, pc) of the native guard detail (either may be None)."""
    f = nat.final
    if f['kind'] != 'guard':
        return None, None
    inner = f['detail'].get('detail')
    if not isinstance(inner, dict):
        return None, None
    return inner.get('address'), inner.get('pc')


def guard_prefix(nat, a, b, begin, srv):
    """Execution equality up to the fault: the C++ run from the phase start to the last G2 block start the native run reached (first arrival) before its guard / the C++ rejection point is
    compared with the native state at that PC (full RAM / 16 registers / PVC / ordered ports / reads).  'trivial' when the phase has no later block start."""
    seq = [pc for k in range(a, b + 1) for pc in nat.pieces[k]['pcs']]
    first_idx = {}
    for i, pc in enumerate(seq):
        if pc in ENV[0].starts and pc not in first_idx:
            first_idx[pc] = i
    cands = [(i, pc) for pc, i in first_idx.items() if i > 0 and pc != begin['pc']]
    if not cands:
        return dict(kind='trivial')
    _, target = max(cands)
    ns = nat.states[nat.pieces[a]['start']]
    n2 = native_flow(ns, (target,), O.GLOBAL['fix_limit'])
    if n2.final['kind'] != 'stop' or n2.final['detail']['pc'] != target:
        return dict(kind='native-not-reached', pc=target)
    nports, next_ext = native_phase_expect(n2, 0, len(n2.pieces) - 1)
    seg = cpp_segment(srv, begin, target)
    if seg['kind'] != 'ok':
        return dict(kind='cpp-%s' % seg['kind'], error=seg.get('error'), pc=target)
    d = compare_ok_segment(seg, begin, n2.states[-1], nports, next_ext)
    return dict(kind='ok' if not d else 'DIFF', diffs=d, pc=target)


def explain_error(nat, a, b, begin, target, seg, gk, units):
    """Classify a checked C++ error of one phase with evidence from the diagnostic copy (the PC at which the production API rejected) and the native run.

    classes: table (native guard kind -> reviewed error of GUARD_TABLE), unknown-carry-boundary (a contract consumer reached with an Unknown C), interior-landing (a computed jump into a unit
    block interior), caller-x-2986 (documented cue wrapper limitation), native-unmasked-address (Unicorn lacks the 68000 24 bit address mask; native read-unmapped above 16 MiB), unrouted /
    checked-callee (black box code the C++ rejects at a PC the native run executed).  `ok` means the evidence holds; the class names a deliberate / documented boundary, never an equality."""
    err = seg['error']
    dseg = cpp_segment(dserver(), begin, target)
    derr = dseg.get('error') if dseg['kind'] == 'error' else None
    dpc = dseg.get('diag_pc') if dseg['kind'] == 'error' else None
    reached = reached_pcs(nat, a, b)
    addr, gpc = guard_detail(nat)
    extra = set()
    for v in (addr, gpc):
        if isinstance(v, int):
            extra.add(v)
            extra.add(v & 0xffffff)
    final_pc = nat.states[nat.pieces[b]['end']]['pc']
    extra.add(final_pc)
    ev = dict(error=err, diag_error_same=(derr == err), diag_pc=dpc, native_guard=gk, native_reached_diag_pc=(dpc in reached or dpc in extra), preserved=seg['preserved'])
    if not seg['preserved']:
        return dict(cls='not-preserved', ok=False, ev=ev)
    if derr != err or dpc is None:
        return dict(cls='diagnostic-mismatch', ok=False, ev=ev)
    seen = ev['native_reached_diag_pc']
    if err in UNKNOWN_CARRY.values():
        cons = dpc in ENV[0].consumers
        ev['consumer_in_contract_or_model'] = cons
        return dict(cls='unknown-carry-boundary', ok=bool(seen and cons), ev=ev)
    if err == CASTER_2986:
        return dict(cls='caller-x-2986', ok=bool(seen and 0x2986 in reached), ev=ev)
    if gk == 'read-unmapped' and isinstance(addr, int) and addr > 0xffffff:
        ev['native_address'] = addr
        ev['masked_address'] = addr & 0xffffff
        return dict(cls='native-unmasked-address', ok=True, ev=ev)
    if err in UNSUPPORTED_UNIT.values():
        u = [k for k, v in UNSUPPORTED_UNIT.items() if v == err][0]
        inside = any(lo <= dpc < hi for lo, hi in ENV[0].contracts[u]['ranges'])
        ev['landing_inside_unit_ranges'] = inside
        ev['landing_is_block_start'] = dpc in ENV[0].starts
        return dict(cls='interior-landing', ok=bool(seen and inside and dpc not in ENV[0].starts), ev=ev)
    if gk is not None and err in GUARD_TABLE.get(gk, ()):
        return dict(cls='table', ok=bool(seen), ev=ev)
    if units == [0]:
        # black box code (no G2 unit code): the C++ rejects it at a PC the native run executed; the error string is reported per string
        return dict(cls='checked-callee', ok=bool(seen), ev=ev)
    return dict(cls='unexplained', ok=False, ev=ev)


def run_cpp_flow(srv, nat, st, carry0, tag, declared_carry=True, with_whole=False):
    """Compare one native cont flow with the C++ chain and the C++ continuous runs.

    Phases: the native pieces (merged when the boundary PC occurs earlier in the phase).  Chain: every phase resumes from the previous actual C++ output.  When a black box phase (no G2 unit
    code, e.g. the callback entry of a later, not yet routed unit) cannot be executed (a documented checked error, see BLACKBOX_ALLOWED), the chain is broken: the next phase starts from the
    declared native boundary state (Known carry = exact native C of the MOVE SR probe), is counted as declared and is compared like the others.  Continuous: the whole flow from the start
    (always tried) and, for every maximal run of >= 2 consecutive successful phases of a broken chain, one continuous C++ run over that run; every continuous result is also compared with
    the chain.  A checked error of a phase is classified by explain_error with diagnostic-PC evidence (never silently accepted)."""
    kind = nat.final['kind']
    res = dict(tag=tag, native=native_summary(nat), pieces=len(nat.pieces), errors=[], carry_checked=0, carry_unknown=0, carry_bad=0, phases=0, merged=0, phase_real=0, phase_declared=0,
               phase_blocked=0, unit_pieces=sum(1 for p in nat.pieces if p['unit']), unit_pieces_ok=0, unit_phase_ok=0, unit_phase_real=0, cont_runs=0, cont_match=0, cont_blocked=0, cont_vs_chain=0,
               boundary=None, blocked_class=[])
    nat_waits = native_wait_rows(nat.waits)
    groups = phase_groups(nat)
    res['phases'] = len(groups)
    res['merged'] = sum(1 for a, b in groups if b > a)
    cur = start_state(st, carry0)
    chain_intact = True
    results = []                 # per phase: dict(kind ok|blocked|guard, begin, seg, a, b, units)
    status = 'match'
    for gi, (a, b) in enumerate(groups):
        last = gi == len(groups) - 1
        guard_phase = last and kind != 'stop'
        begin_idx = nat.pieces[a]['start']
        end_idx = nat.pieces[b]['end']
        units = phase_unit_set(nat, a, b)
        if chain_intact:
            begin = cur
            declared = False
        else:
            ns = nat.states[begin_idx]
            begin = start_state(ns, carry_of(ns['ccr']) if (declared_carry and ns['ccr'] is not None) else 0)
            declared = True
        target = IMPOSSIBLE_STOP if guard_phase else nat.states[end_idx]['pc']
        seg = cpp_segment(srv, begin, target)
        if guard_phase:
            gk = nat.final['detail'].get('kind') if kind == 'guard' else kind
            gaddr, gpc_ = guard_detail(nat)
            if gk == 'read-unmapped' and isinstance(gaddr, int) and gaddr > 0xffffff:
                # Unicorn does not mask the 68000 address bus to 24 bits: the native model faults on a 32 bit address that the real CPU (and the C++) read at gaddr & ffffff.  Not comparable.
                res['boundary'] = dict(cls='native-unmasked-address', ok=True, phase=gi, declared=declared, units=units,
                                       ev=dict(native_address=gaddr, masked_address=gaddr & 0xffffff, cpp_result=(seg['error'] if seg['kind'] == 'error' else seg['kind'])))
                res['split_error'] = seg['error'] if seg['kind'] == 'error' else None
                res['split_pair'] = [gk, res['split_error'] or seg['kind']]
                status = 'guard-boundary:native-unmasked-address'
                pf = guard_prefix(nat, a, b, begin, srv)
                res['guard_prefix'] = pf
                if pf['kind'] not in ('ok', 'trivial'):
                    res['errors'].append(('guard-prefix', pf))
            elif seg['kind'] == 'error':
                ex = explain_error(nat, a, b, begin, target, seg, gk, units)
                res['split_error'] = seg['error']
                res['split_pair'] = [gk, seg['error']]
                res['boundary'] = dict(cls=ex['cls'], ok=ex['ok'], phase=gi, declared=declared, units=units, ev=ex['ev'])
                if ex['ok']:
                    pf = guard_prefix(nat, a, b, begin, srv)
                    res['guard_prefix'] = pf
                    if pf['kind'] not in ('ok', 'trivial'):
                        res['errors'].append(('guard-prefix', pf))
                    status = 'guard-match' if ex['cls'] == 'table' else 'guard-boundary:%s' % ex['cls']
                    res['phase_declared' if declared else 'phase_real'] += 1
                    res['unit_pieces_ok'] += sum(1 for k in range(a, b + 1) if nat.pieces[k]['unit'])
                    if units != [0]:
                        res['unit_phase_ok'] += 1
                        res['unit_phase_real'] += 0 if declared else 1
                else:
                    status = 'guard-unexplained'
                    res['errors'].append(('split-guard', gk, seg['error'], ex['cls']))
            elif seg['kind'] == 'ok':
                status = 'cpp-completed-native-%s' % gk
                res['errors'].append(('cpp-completed-guard', gk))
            else:
                status = 'DIFF'
                res['errors'].append(('guard-phase', seg['kind']))
            results.append(dict(kind='guard', begin=begin, units=units))
            break
        if seg['kind'] == 'error':
            ex = explain_error(nat, a, b, begin, target, seg, None, units)
            if units == [0] and ex['ok'] and seg['error'] in BLACKBOX_ALLOWED and ex['cls'] in ('checked-callee', 'caller-x-2986', 'table'):
                res['phase_blocked'] += 1
                res['blocked_class'].append(dict(error=seg['error'], cls=ex['cls'], diag_pc=ex['ev']['diag_pc']))
                res.setdefault('blocked_reason', []).append(seg['error'])
                res.setdefault('blocked_from', []).append(begin['pc'])
                chain_intact = False
                results.append(dict(kind='blocked', units=units))
                continue
            if ex['ok'] and ex['cls'] in ('unknown-carry-boundary', 'interior-landing'):
                # a documented checked boundary inside a native-successful phase: the consumer was reached with an Unknown C (the producer is a C-unknown instruction) / a computed landing in a block interior
                res['boundary'] = dict(cls=ex['cls'], ok=True, phase=gi, declared=declared, units=units, ev=ex['ev'])
                status = 'boundary:%s' % ex['cls']
                res['split_error'] = seg['error']
                break
            status = 'cpp-error@phase%d' % gi
            res['errors'].append(('phase', gi, units, 'error', seg.get('error'), declared, ex['cls']))
            res['split_error'] = seg.get('error')
            break
        if seg['kind'] != 'ok':
            status = 'cpp-%s@phase%d' % (seg['kind'], gi)
            res['errors'].append(('phase', gi, units, seg['kind'], seg.get('error'), declared))
            break
        nports, next_ext = native_phase_expect(nat, a, b)
        d = compare_ok_segment(seg, begin, nat.states[end_idx], nports, next_ext)
        if d:
            status = 'mismatch@phase%d:%s' % (gi, ','.join(d))
            res['errors'].append(('phase', gi, units, d, declared))
            break
        carry_check(res, seg['cur'], nat.states[end_idx])
        res['phase_declared' if declared else 'phase_real'] += 1
        up = sum(1 for k in range(a, b + 1) if nat.pieces[k]['unit'])
        res['unit_pieces_ok'] += up
        if units != [0]:
            res['unit_phase_ok'] += 1
            res['unit_phase_real'] += 0 if declared else 1
        results.append(dict(kind='ok', begin=begin, seg=seg, a=a, b=b, units=units, declared=declared, end_idx=end_idx))
        cur = seg['cur']
        if declared:
            chain_intact = True            # re-entered from the declared native state: the chain continues from the C++ output again
    res['split'] = status
    # ---------------------------------------------------------------- continuous runs
    # (1) the whole flow from the start (when every phase of the chain was real, it must equal the chain result)
    fin = nat.states[-1]
    stop = nat.final['detail']['pc'] if kind == 'stop' else IMPOSSIBLE_STOP
    whole_start = start_state(st, carry0)
    seg = cpp_segment(srv, whole_start, stop)
    res['cont_runs'] += 1
    res['cont_kind'] = seg['kind']
    # The first documented checked boundary of the split chain (the first blocked black box phase, else the terminal boundary): the continuous run must stop at the same PC with the same error.
    first = None
    if res['blocked_class']:
        first = (res['blocked_class'][0]['error'], res['blocked_class'][0]['diag_pc'])
    elif res['boundary'] and res['boundary']['cls'] != 'native-unmasked-address':
        first = (res['split_error'], res['boundary']['ev'].get('diag_pc'))
    def same_boundary(sg):
        if first is None or sg['kind'] != 'error' or not sg['preserved'] or sg['error'] != first[0]:
            return False
        dseg = cpp_segment(dserver(), whole_start, stop)
        return dseg['kind'] == 'error' and dseg['error'] == first[0] and dseg.get('diag_pc') == first[1]
    if kind == 'stop':
        if seg['kind'] == 'ok':
            d = compare_ok_segment(seg, whole_start, fin, native_ports([e for e in nat.ports_all]), sum(p['ext'] for p in nat.pieces))
            if not waits_equal(seg['waits'], nat_waits):
                d.append('waits')
            if d:
                res['cont'] = 'mismatch:' + ','.join(d)
                res['errors'].append(('cont', d))
            else:
                res['cont'] = 'match'
                res['cont_match'] += 1
                carry_check(res, seg['cur'], fin)
        elif same_boundary(seg):
            res['cont'] = 'blocked-unrouted-blackbox' if res['phase_blocked'] else 'boundary-same-error'
            res['cont_error'] = seg['error']
            res['cont_blocked'] += 1
            seg = None
        else:
            res['cont'] = 'cpp-%s' % seg['kind']
            res['cont_error'] = seg.get('error')
            res['errors'].append(('cont', seg['kind'], seg.get('error'), first))
    else:
        gk = nat.final['detail'].get('kind') if kind == 'guard' else kind
        unmasked = bool(res['boundary'] and res['boundary']['cls'] == 'native-unmasked-address' and not res['phase_blocked'])
        if seg['kind'] == 'error':
            res['cont_error'] = seg['error']
            res['pair'] = [gk, seg['error']]
            if unmasked:
                res['cont'] = 'guard-match' if seg['preserved'] else 'guard-unexpected'
                res['cont_match'] += 1 if seg['preserved'] else 0
            elif same_boundary(seg):
                res['cont'] = 'blocked-unrouted-blackbox' if res['phase_blocked'] else 'guard-match'
                if res['phase_blocked']:
                    res['cont_blocked'] += 1
                else:
                    res['cont_match'] += 1
            else:
                res['cont'] = 'guard-unexpected'
                res['errors'].append(('cont-guard', gk, seg['error'], first))
        else:
            res['cont'] = 'cpp-completed-native-%s' % gk
            if not unmasked:
                res['errors'].append(('cont-completed-guard', gk))
        if res.get('split_pair') and not res.get('pair'):
            res['pair'] = res['split_pair']
    whole = seg
    # (2) the chain equals the whole run when the chain is intact from the start to the end
    if kind == 'stop' and seg is not None and seg['kind'] == 'ok' and results and all(r['kind'] == 'ok' and not r['declared'] for r in results):
        last_seg = results[-1]['seg']
        allports = []
        allreads = 0
        for r in results:
            allports += r['seg']['ports']
            allreads += r['seg']['reads']
        c1, c2 = last_seg['cur'], seg['cur']
        if c1 == c2 and allports == seg['ports'] and allreads == seg['reads']:
            res['cont_vs_chain'] += 1
        else:
            res['errors'].append(('cont-vs-chain',))
    # (3) continuous over each maximal run (>= 2) of successful phases after a break
    i = 0
    n = len(results)
    while i < n:
        if results[i]['kind'] != 'ok':
            i += 1
            continue
        j = i
        while j + 1 < n and results[j + 1]['kind'] == 'ok' and results[j + 1]['declared'] is False:
            j += 1
        if j > i and not (i == 0 and results[0]['declared'] is False and j == n - 1):
            begin = results[i]['begin']
            tgt = results[j]['seg']['cur']['pc']
            r2 = cpp_segment(srv, begin, tgt)
            res['cont_runs'] += 1
            ports_all = []
            reads_all = 0
            for k in range(i, j + 1):
                ports_all += results[k]['seg']['ports']
                reads_all += results[k]['seg']['reads']
            if r2['kind'] == 'ok' and r2['cur'] == results[j]['seg']['cur'] and r2['ports'] == ports_all and r2['reads'] == reads_all:
                res['cont_vs_chain'] += 1
                res['cont_match'] += 1
            else:
                res['errors'].append(('cont-run', i, j, r2['kind'], r2.get('error')))
        i = j + 1
    final_cur = None
    if kind == 'stop' and results and results[-1]['kind'] == 'ok' and results[-1]['end_idx'] == len(nat.states) - 1:
        final_cur = results[-1]['seg']['cur']
    if with_whole:
        wr = None
        if whole is not None:
            wr = dict(kind=whole['kind'], stop=stop, cur=whole.get('cur'), ports=whole.get('ports'), reads=whole.get('reads'), error=whole.get('error'))
        return res, final_cur, wr
    return res, final_cur


def flow_class(res):
    """Single classification string of a flow result."""
    if res['errors']:
        return 'DIFF'
    kind = res['native']['kind']
    split = res['split']
    cont = res['cont']
    if kind == 'stop':
        if split == 'match' and cont in ('match', 'blocked-unrouted-blackbox'):
            return 'match' if res['phase_blocked'] == 0 else 'match-partial'
        if split.startswith('boundary:') and cont in ('boundary-same-error', 'blocked-unrouted-blackbox'):
            return 'deliberate:' + split.split(':', 1)[1]
        return 'DIFF'
    if split == 'guard-match' and cont in ('guard-match', 'blocked-unrouted-blackbox'):
        return 'guard:%s->%s' % (res['native']['guard'] or kind, res['split_error'])
    if split.startswith('guard-boundary:') and (cont in ('guard-match', 'blocked-unrouted-blackbox') or cont.startswith('cpp-completed-native')):
        return 'guard-deliberate:%s' % split.split(':', 1)[1]
    return 'DIFF'


