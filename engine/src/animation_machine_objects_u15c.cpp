// Objects F4 U15c (196 block starts): the terrain slope table entries 45b12 (U08b 463b4/464c6) and 45b1a (U15a 46670/46748), 45b22,
// the jump 45b28 (JMP 45b2c(PC,D7.W), all 96 BRA.W entries 45b2c..45ca8) and the 96 target bodies 45cac..461de (ORI.W #m,54aa(A5);
// MOVE.W #v,54ac(A5); RTS). 45b28 moves to the computed PC 45b2c+D7.W through the routing. U15c has no call, no carry consumer
// across blocks and no known-carry producer; it reads and writes the work RAM WORDs 54aa/54ac only and writes no port.
bool animation_objects_u15c_block(AnimationMachineContext& c) {
    AnimationMachineState& r=c.s;
    switch(r.pc) {
    // CMPI.W #174,D7; BEQ.W 45e6c (target body k = 20), otherwise fall through to 45b1a.
    case 0x45b12:r.pc=(r.d[7]&65535U)==OU15C_SPECIAL?0x45e6c:0x45b1a;return true;
    // CMPI.W #174,D7; BNE.W 45b28.
    case 0x45b1a:r.pc=(r.d[7]&65535U)!=OU15C_SPECIAL?0x45b28:0x45b22;return true;
    // TST.L D3; BGT.W 46198 (signed LONG D3 > 0: N clear and Z clear, V = 0 after TST).
    case 0x45b22:r.pc=(r.d[3]!=0U && (r.d[3]&0x80000000U)==0U)?0x46198:0x45b28;return true;
    // JMP 45b2c(PC,D7.W) (computed PC through the routing).
    case 0x45b28:r.pc=am_index(OU15C_TABLE,r.d[7]);return true;
    default:
        // Table entries 45b2c+4k: BRA.W to the transcribed target. The displacement WORDs are interior PCs.
        if(r.pc>=OU15C_TABLE && r.pc<OU15C_TABLE+4U*OU15C_ENTRIES && ((r.pc-OU15C_TABLE)&3U)==0){
            r.pc=OU15C_TARGETS[(r.pc-OU15C_TABLE)>>2];return true;
        }
        // Target bodies 45cac+e*k: ORI.W #m,54aa(A5); MOVE.W #v,54ac(A5); RTS. Their inner PCs are interior PCs.
        if(r.pc>=OU15C_BODY && r.pc<OU15C_BODY+OU15C_BODY_SIZE*OU15C_ENTRIES && (r.pc-OU15C_BODY)%OU15C_BODY_SIZE==0){
            const unsigned int k=(r.pc-OU15C_BODY)/OU15C_BODY_SIZE;std::uint32_t value=0;
            if(!am_read(c,am_index(r.a[5],OU15C_FLAGS),2,value))return false;
            if(!am_write(c,am_index(r.a[5],OU15C_FLAGS),2,(value|OU15C_BODIES[k][0])&65535U))return false;
            if(!am_write(c,am_index(r.a[5],OU15C_ANGLE),2,OU15C_BODIES[k][1]))return false;
            return am_return(c);
        }
        return am_error(c,"unsupported animation objects u15c PC");
    }
}
